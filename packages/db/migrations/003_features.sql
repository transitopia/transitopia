-- The feature registry (docs/DESIGN.md#feature-ids): persistent IDs for stations, exchanges, stops
-- and routes (vehicles and cycling features later), refs to the source records they come from,
-- which station or exchange a stop belongs to, reconciliation flags and admin changes. Statistics
-- gain the feed version they were derived from, so views can follow a route or stop across feed
-- versions through its refs.

create extension if not exists btree_gist;

-- Operators (config/operators/<id>/operator.json): the server upserts them when it starts, before
-- the feeds, which now reference theirs.
create table operators (
  id text primary key,
  name text not null
);
insert into operators (id, name) values ('translink', 'TransLink'), ('bc-transit', 'BC Transit');

alter table feeds add column operator_id text references operators;
update feeds set operator_id = case agency when 'TransLink' then 'translink'
                                           when 'BC Transit' then 'bc-transit' end;
alter table feeds alter column operator_id set not null;
alter table feeds drop column agency;

create table features (
  -- <prefix>-<8 random Crockford base32 characters>; the prefix matches the kind
  -- (packages/shared/src/features.ts, checked where these rows are written).
  id text primary key check (id ~ '^[a-z]{2,3}-[0-9a-hjkmnp-tv-z]{8}$'),
  kind text not null check (kind in ('station', 'exchange', 'stop', 'route', 'vehicle',
                                     'cycling-route', 'cycling-way', 'bike-parking',
                                     'bikeshare-station')),
  -- Routes, stops and vehicles; null for places (stations, exchanges) and cycling features.
  operator_id text references operators,
  -- The feed a stop or route comes from.
  feed_id text references feeds,
  -- A stop's station or exchange (docs/DESIGN.md#relationships-between-features). Set when the stop
  -- is first minted and then changed only by an admin (feature_changes).
  parent_id text references features,
  name text not null,
  -- A point (stations, exchanges, stops) or a line (cycling); null for routes and vehicles.
  geom geography,
  status text not null default 'active' check (status in ('active', 'retired', 'merged')),
  merged_into text references features,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check ((status = 'merged') = (merged_into is not null))
);
create index on features using gist (geom);
create index on features (parent_id);
create index on features (feed_id, kind);

-- Feed versions in the order we archived them, so refs can hold over a range of them. Existing
-- rows are numbered by when they were fetched (a feed's versions can share a start date, and their
-- names don't sort by time: TransLink's 26DEC_… is before 26SEP_…), then start date and version.
alter table gtfs_feeds add column seq integer;
update gtfs_feeds g set seq = n.seq
from (select feed_id, version,
             row_number() over (order by fetched_at, start_date, version, feed_id) as seq
      from gtfs_feeds) n
where g.feed_id = n.feed_id and g.version = n.version;
alter table gtfs_feeds alter column seq set not null;
alter table gtfs_feeds alter column seq add generated by default as identity;
select setval(pg_get_serial_sequence('gtfs_feeds', 'seq'), coalesce(max(seq), 0) + 1, false)
from gtfs_feeds;
alter table gtfs_feeds add constraint gtfs_feeds_seq_key unique (seq);
-- When reconciliation took the version in (apps/server/src/features/reconcile.ts).
alter table gtfs_feeds add column reconciled_at timestamptz;

create table feature_refs (
  id bigint generated always as identity primary key,
  feature_id text not null references features,
  scheme text not null,
  -- The feed (GTFS schemes), operator or GBFS system; '' for schemes without one.
  namespace text not null default '',
  ref text not null,
  -- gtfs_feeds.seq of the versions it holds in, for the GTFS schemes; unbounded for the others.
  versions int4range not null default '(,)',
  origin text not null check (origin in ('reconcile', 'admin', 'import')),
  created_at timestamptz not null default now(),
  -- A ref names one feature in each version.
  exclude using gist (scheme with =, namespace with =, ref with =, versions with &&)
);
create index on feature_refs (feature_id);

-- Every admin change to the registry, so a wrong one can be traced and undone.
create table feature_changes (
  id bigint generated always as identity primary key,
  feature_id text not null references features,
  action text not null,       -- 'set-parent', 'retire', 'merge', 'move-ref', 'rename', …
  before jsonb,
  after jsonb,
  user_id bigint references users,
  created_at timestamptz not null default now()
);
create index on feature_changes (feature_id);

-- What reconciliation wasn't sure of, for an admin to resolve.
create table feature_flags (
  id bigint generated always as identity primary key,
  feature_id text not null references features,  -- the feature minted or changed
  candidates text[] not null default '{}',       -- features it may be the same as
  reason text not null,                          -- 'code-moved-far', 'exchange-replaced', …
  detail jsonb,
  state text not null default 'open' check (state in ('open', 'resolved')),
  resolution text,                               -- 'kept', 'merged:<id>', 'moved:<id>', 'retired'
  resolved_by bigint references users,
  created_at timestamptz not null default now(),
  resolved_at timestamptz
);
create index on feature_flags (feature_id, reason);

-- Statistics name the feed version they were derived from. For existing rows, that's the version
-- the daily job would have picked when it computed them (feedZipFor in packages/data/src/gtfs-day.ts:
-- the newest covering the service date, by start date then version, among the versions fetched by
-- then; route_stats_daily.computed_at says when). Versions fetched later can cover the same dates
-- (TransLink's all start 2026-09-07), so the newest version overall would be wrong for older days.
alter table observed_stop_times add column feed_version text;
alter table route_stats_daily add column feed_version text;
create temporary table stats_versions on commit drop as
select d.feed_id, d.service_date,
       coalesce(
         (select g.version from gtfs_feeds g
          where g.feed_id = d.feed_id and d.service_date between g.start_date and g.end_date
            and g.fetched_at <= d.computed_at
          order by g.start_date desc, g.version desc limit 1),
         (select g.version from gtfs_feeds g
          where g.feed_id = d.feed_id and d.service_date between g.start_date and g.end_date
          order by g.fetched_at, g.start_date desc, g.version desc limit 1)) as version
from (select k.feed_id, k.service_date, coalesce(c.computed_at, now()) as computed_at
      from (select distinct feed_id, service_date from observed_stop_times
            union select feed_id, service_date from route_stats_daily) k
      left join (select feed_id, service_date, max(computed_at) as computed_at
                 from route_stats_daily group by feed_id, service_date) c
        on c.feed_id = k.feed_id and c.service_date = k.service_date) d;
update observed_stop_times s set feed_version = v.version
from stats_versions v where s.feed_id = v.feed_id and s.service_date = v.service_date;
update route_stats_daily s set feed_version = v.version
from stats_versions v where s.feed_id = v.feed_id and s.service_date = v.service_date;

-- A route's and a stop's statistics across feed versions, by feature.
create view route_stats_daily_by_feature as
select r.feature_id as route, s.*
from route_stats_daily s
join gtfs_feeds g on g.feed_id = s.feed_id and g.version = s.feed_version
join feature_refs r
  on r.scheme = 'gtfs-route' and r.namespace = s.feed_id and r.ref = s.route_id
 and r.versions @> g.seq;

create view observed_stop_times_by_feature as
select r.feature_id as stop, s.*
from observed_stop_times s
join gtfs_feeds g on g.feed_id = s.feed_id and g.version = s.feed_version
join feature_refs r
  on r.scheme = 'gtfs-stop' and r.namespace = s.feed_id and r.ref = s.stop_id
 and r.versions @> g.seq;
